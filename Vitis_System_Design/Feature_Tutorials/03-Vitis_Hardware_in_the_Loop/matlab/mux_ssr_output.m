function chnlzr_out = mux_ssr_output(chnlzr_ssr_out)
% Reorders 8 SSR output streams from the channelizer DFT stage into
% 16 individual channel outputs. Scales from int16 representation.

ssr_combined = 2^-15 * chnlzr_ssr_out(:);

N = length(ssr_combined);

chnlzr_out = [ ...
    ssr_combined(reshape([(1:4:(N/8))' ((N/8+1):4:(N/4))']',N/16,1)) ...
    ssr_combined(reshape([(2:4:(N/8))' ((N/8+2):4:(N/4))']',N/16,1)) ...
    ssr_combined(reshape([(3:4:(N/8))' ((N/8+3):4:(N/4))']',N/16,1)) ...
    ssr_combined(reshape([(4:4:(N/8))' ((N/8+4):4:(N/4))']',N/16,1)) ...
    ssr_combined(reshape([((N/4+1):4:(3*N/8))' ((3*N/8+1):4:(N/2))']',N/16,1)) ...
    ssr_combined(reshape([((N/4+2):4:(3*N/8))' ((3*N/8+2):4:(N/2))']',N/16,1)) ...
    ssr_combined(reshape([((N/4+3):4:(3*N/8))' ((3*N/8+3):4:(N/2))']',N/16,1)) ...
    ssr_combined(reshape([((N/4+4):4:(3*N/8))' ((3*N/8+4):4:(N/2))']',N/16,1)) ...
    ssr_combined(reshape([((N/2+1):4:(5*N/8))' ((5*N/8+1):4:(3*N/4))']',N/16,1)) ...
    ssr_combined(reshape([((N/2+2):4:(5*N/8))' ((5*N/8+2):4:(3*N/4))']',N/16,1)) ...
    ssr_combined(reshape([((N/2+3):4:(5*N/8))' ((5*N/8+3):4:(3*N/4))']',N/16,1)) ...
    ssr_combined(reshape([((N/2+4):4:(5*N/8))' ((5*N/8+4):4:(3*N/4))']',N/16,1)) ...
    ssr_combined(reshape([((3*N/4+1):4:(7*N/8))' ((7*N/8+1):4:N)']',N/16,1)) ...
    ssr_combined(reshape([((3*N/4+2):4:(7*N/8))' ((7*N/8+2):4:N)']',N/16,1)) ...
    ssr_combined(reshape([((3*N/4+3):4:(7*N/8))' ((7*N/8+3):4:N)']',N/16,1)) ...
    ssr_combined(reshape([((3*N/4+4):4:(7*N/8))' ((7*N/8+4):4:N)']',N/16,1)) ...
    ];

end
